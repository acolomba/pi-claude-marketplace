import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";

import {
  GENERATED_AGENT_MARKER,
  isOwnedAgentFile,
} from "../../extensions/pi-claude-marketplace/bridges/agents/marker.ts";
import { locationsFor } from "../../extensions/pi-claude-marketplace/persistence/locations.ts";

// AG-5 marker bytes are a persisted contract. Independently authored documents
// prove both supported formats remain readable; malformed near-matches remain foreign.
test("AG-5 preserves the current generated marker bytes", () => {
  // arrange
  const expectedMarker = "generatedBy: pi-claude-marketplace";

  // act
  const marker = GENERATED_AGENT_MARKER;

  // assert
  assert.strictEqual(marker, expectedMarker);
});

for (const { format, document } of [
  {
    format: "current provenance",
    document:
      "---\nname: pi-claude-marketplace-tools-reviewer\nprovenance:\n  generatedBy: pi-claude-marketplace\n---\n\nReview.\n",
  },
  {
    format: "legacy body-comment",
    document:
      "---\nname: pi-claude-marketplace-tools-reviewer\n---\n\n<!-- generated by pi-claude-marketplace -->\nReview.\n",
  },
]) {
  test(`AG-5 recognizes existing ${format} bytes without changing them`, async (t) => {
    // arrange
    const root = await mkdtemp(path.join(tmpdir(), "agent-marker-contract-"));
    t.after(async () => rm(root, { recursive: true, force: true }));
    const target = path.join(root, "pi-claude-marketplace-tools-reviewer.md");
    await writeFile(target, document);

    // act
    const ownership = await isOwnedAgentFile(target);

    // assert
    assert.deepStrictEqual(ownership, { ok: true });
    assert.strictEqual(await readFile(target, "utf8"), document);
  });
}

test("AG-5 refuses a near-match basename despite a valid legacy marker", async (t) => {
  // arrange
  const root = await mkdtemp(path.join(tmpdir(), "agent-marker-contract-"));
  t.after(async () => rm(root, { recursive: true, force: true }));
  const target = path.join(root, "pi-claude-marketplac-tools-reviewer.md");
  const document = "<!-- generated by pi-claude-marketplace -->\nReview.\n";
  await writeFile(target, document);

  // act
  const ownership = await isOwnedAgentFile(target);

  // assert
  assert.deepStrictEqual(ownership, {
    ok: false,
    reason:
      'target filename "pi-claude-marketplac-tools-reviewer.md" does not start with "pi-claude-marketplace-"',
  });
  assert.strictEqual(await readFile(target, "utf8"), document);
});

for (const { format, document } of [
  { format: "current", document: "generatedBy: pi-claude-marketplac\n" },
  { format: "legacy", document: "<!-- generated by pi-claude-marketplac -->\n" },
]) {
  test(`AG-5 refuses a near-match ${format} marker on a correctly named file`, async (t) => {
    // arrange
    const root = await mkdtemp(path.join(tmpdir(), "agent-marker-contract-"));
    t.after(async () => rm(root, { recursive: true, force: true }));
    const target = path.join(root, "pi-claude-marketplace-tools-reviewer.md");
    await writeFile(target, document);

    // act
    const ownership = await isOwnedAgentFile(target);

    // assert
    assert.deepStrictEqual(ownership, {
      ok: false,
      reason: `target ${target} is missing the generated marker`,
    });
    assert.strictEqual(await readFile(target, "utf8"), document);
  });
}

